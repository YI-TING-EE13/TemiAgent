    parser.add_argument("--reasoning-effort", choices=EFFORTS, help="Optional assertion of the running Resident effort; does not change it.")
    parser.add_argument("--context-length", type=int, help="Optional assertion of current context length; otherwise auto-detect.")
    parser.add_argument("--resident-url", default="http://127.0.0.1:8765")
