def get_json(url: str):
    with urlopen(url, timeout=10) as response:
        return json.load(response)


def option(argv: list[str], name: str, default=None):
    for index, value in enumerate(argv):
        if value == name:
            return argv[index + 1]
        if value.startswith(name + "="):
            return value.split("=", 1)[1]
    return default


def process(pid: int, expected: str) -> tuple[dict, list[str], dict]:
    """Read local identity; never persist full argv/environment or credentials."""
    base = Path("/proc") / str(pid)
    argv = base.joinpath("cmdline").read_bytes().decode().rstrip("\0").split("\0")
    cwd = base.joinpath("cwd").resolve(strict=True)
    if not any((cwd / token).resolve() == (ROOT / expected).resolve() for token in argv):
        raise ValueError(f"PID {pid} is not the expected {expected}")
    executable = base.joinpath("exe").resolve(strict=True)
    if not executable.name.startswith("python"):
        raise ValueError(f"PID {pid} is not a Python service")
    env = dict(item.split("=", 1) for item in base.joinpath("environ").read_bytes().decode().split("\0") if "=" in item)
    identity = {"pid": pid, "cwd": str(cwd), "exe": str(executable),
                "start_ticks": base.joinpath("stat").read_text().split(") ", 1)[1].split()[19]}
    return identity, argv, env


def effective_bridge_values(identity: dict, argv: list[str], env: dict) -> dict:
    """Match the Bridge's simple env-file parsing, with process env taking precedence."""
    path = Path(identity["cwd"]) / option(argv, "--env-file", ".env")
    values = {}
    if path.exists():
        for raw in path.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip().strip('"').strip("'")
    return {**values, **env}


def verify_runtime(args) -> dict:
    """Fail closed on missing or contradictory local configuration evidence."""
    resident_id, argv, env = process(args.resident_pid, "tools/hermes_resident_server.py")
    parsed = urlsplit(args.resident_url)
    if parsed.scheme != "http" or parsed.hostname not in {"127.0.0.1", "localhost", "::1"} or parsed.path not in {"", "/"}:
        raise ValueError("Resident must be a local HTTP origin for PID verification")
    port = parsed.port or 80
    listeners = subprocess.check_output(["ss", "-H", "-ltnp", f"sport = :{port}"], text=True, timeout=10)
    if len(listeners.splitlines()) != 1 or not re.search(rf"pid={args.resident_pid},", listeners):
        raise ValueError("Resident listener does not match the supplied PID")
    effort = option(argv, "--reasoning-effort", "default")
    if effort not in EFFORTS or (args.reasoning_effort is not None and effort != args.reasoning_effort):
        raise ValueError("Resident reasoning effort does not match; restart through its owner first")
    if env.get("HERMES_EXPERIMENTAL_CONTEXT", "false").lower() not in {"0", "false", "no", "off"}:
        raise ValueError("experimental dialogue Context must be disabled for this benchmark")
    health = get_json(args.resident_url.rstrip("/") + "/health")
    model = health.get("model")
    context = health.get("context_length")
    if (health.get("status") != "ok" or not isinstance(model, str) or not model.strip()
            or not isinstance(context, int) or isinstance(context, bool) or context <= 0
            or health.get("compression_context_length") != context
            or (args.model is not None and model != args.model)
            or (args.context_length is not None and context != args.context_length)):
        raise ValueError("Resident model/context/health does not match")
    # OpenAI /v1/models may list downloaded models/aliases; use native loaded instances.
    api = urlsplit(health.get("base_url", ""))
    if api.scheme != "http" or api.hostname not in {"127.0.0.1", "localhost", "::1"} or api.username or api.password:
        raise ValueError("expected a local LM Studio API")
    native = get_json(f"{api.scheme}://{api.netloc}/api/v1/models")
    loaded = [(model, instance) for model in native.get("models", [])
              if model.get("type") in {"llm", "vlm"} for instance in model.get("loaded_instances", [])]
    if (len(loaded) != 1 or not loaded[0][0].get("key")
            or (args.model_key is not None and loaded[0][0].get("key") != args.model_key)
            or loaded[0][1].get("id") != model
            or loaded[0][1].get("config", {}).get("context_length") != context):
        raise ValueError("LM Studio loaded model/context is missing, ambiguous or mismatched")
    bridge_id, bridge_argv, bridge_env = process(args.bridge_pid, "hermes_temi_bridge/.venv/bin/hermes-temi-bridge")
    config = effective_bridge_values(bridge_id, bridge_argv, bridge_env)
    def bridge_path(key, default):
        return (Path(bridge_id["cwd"]) / config.get(key, default)).resolve()
    if (config.get("HERMES_INVOKE_MODE") != "http"
            or config.get("HERMES_HTTP_URL") != args.resident_url.rstrip("/") + "/invoke"
            or config.get("CARE_CONTEXT_ENABLED", "true").lower() not in {"0", "false", "no", "off"}
            or config.get("TRACE_ENABLED", "true").lower() not in {"1", "true", "yes", "on"}
            or bridge_path("LOG_DIR", "logs/events") != args.trace_dir.resolve()
            or config.get("MQTT_BROKER_HOST", "localhost") != args.broker
            or int(config.get("MQTT_BROKER_PORT", "1883")) != args.port
            or args.robot_id not in [value.strip() for value in config.get("ROBOT_ID_ALLOWLIST", "temi-01").split(",")]
            or bridge_path("TEMI_SHARED_BRIDGE_PATH", "temi_shared") != Path(args.bridge_root).resolve()
            or args.shared_root.resolve() != Path(args.bridge_root).resolve()):
        raise ValueError("Bridge route, broker, allowlist, Context, trace or local shared paths do not match")
    if args.cleanup_memory_after_case and bridge_path("MEMORY_DIR", "memory") != args.memory_root.resolve():
        raise ValueError("cleanup memory root is not the Bridge's configured MEMORY_DIR")
    return {"resident": resident_id, "bridge": bridge_id, "model": health["model"],
            "provider": health.get("provider"), "reasoning_effort": effort,
            "context_length": context,
            "loaded_model": {"id": loaded[0][0]["key"], "instance_id": loaded[0][1]["id"],
                             "config": loaded[0][1]["config"],
                             "quantization": loaded[0][0].get("quantization"),
                             "selected_variant": loaded[0][0].get("selected_variant")},
            "health_flags": {key: value for key, value in health.items() if key.endswith("_enabled")},
            "toolsets": health.get("toolsets"), "care_context_enabled": False,
            "experimental_context_enabled": False}


class TimedCapture(action.CommandCapture):
    def __init__(self, *args):
        super().__init__(*args)
        self.published_times = {}
        self.commands = {}

    def publish(self, payload):
        self.published_times[payload["event_id"]] = time.perf_counter()
        return super().publish(payload)

    def wait_for_event(self, event_id, timeout):
        command = super().wait_for_event(event_id, timeout)
        self.commands[event_id] = command
        return command


def read_trace(trace_dir: Path, event_id: str, timeout: float = 3) -> list[dict]:
    """Boundedly await terminal trace flush; never substitute a different event."""
    deadline = time.monotonic() + timeout
    records = []
    while True:
        try:
            records = [json.loads(line) for line in (trace_dir / f"{event_id}.jsonl").read_text().splitlines() if line.strip()]
            if any(item.get("event_id") != event_id for item in records):
                raise ValueError("trace event ID mismatch")
            if any(item.get("stage") in {"event_completed", "event_failed"} for item in records):
                return records
        except (FileNotFoundError, json.JSONDecodeError):
            pass
        if time.monotonic() >= deadline:
            return records
        time.sleep(0.05)


def measurement(row: dict, capture, trace: list[dict]) -> dict:
    stages = {item["stage"]: item for item in trace if "stage" in item}
    invoke = stages.get("hermes_invocation_finished", {})
    payload = invoke.get("payload", {})
    command = capture.commands.get(row["event_id"], {})
    latency = payload.get("hermes_latency_ms")
    latency = latency if isinstance(latency, (int, float)) and not isinstance(latency, bool) and math.isfinite(latency) and latency >= 0 else None
    inference_ok = invoke.get("status") == "ok" and latency is not None and not payload.get("resident_dispatch")
    valid = bool(inference_ok and command and not command.get("fallback_reason")
                 and stages.get("hermes_output_validated", {}).get("status") == "ok"
                 and "event_completed" in stages and "event_failed" not in stages and not row.get("error"))
    received = capture.received_times.get(row["event_id"])
    published = capture.published_times.get(row["event_id"])
    dispatch = round((received - published) * 1000, 3) if received is not None and published is not None else None
    return {**row, "inference_completed": inference_ok, "valid_output": valid,
            "hermes_latency_ms": latency, "dispatch_latency_ms": dispatch,
            "fallback_reason": command.get("fallback_reason"),
            "failure_stage": stages.get("event_failed", {}).get("payload", {}).get("failed_stage"),
            "trace_complete": "event_completed" in stages or "event_failed" in stages}


def summarize(rows: list[dict]) -> dict:
    measured = [row for row in rows if not row["warmup"]]
    valid = [row for row in measured if row["valid_output"]]
    def stats(key):
        values = sorted(row[key] / 1000 for row in valid if row.get(key) is not None)
        return {"n": len(values), "mean_s": statistics.mean(values) if values else None,
                "median_s": statistics.median(values) if values else None,
                "p90_s": values[math.ceil(len(values) * .9) - 1] if values else None,
                "sum_s": sum(values)}
    return {"attempts": len(measured), "inference_completed": sum(row["inference_completed"] for row in measured),
            "valid_outputs": len(valid),
            "consistent_valid_outputs": sum(row["response_action_consistency"] == "CONSISTENT" for row in valid),
            "hermes": stats("hermes_latency_ms"), "dispatch": stats("dispatch_latency_ms")}


def write_reports(directory: Path, rows: list[dict]) -> dict:
    summary = summarize(rows)
    fields = ("case_id", "repetition", "warmup", "event_id", "text", "response_texts", "actual_actions",
              "response_action_consistency", "inference_completed", "valid_output", "hermes_latency_ms",
              "dispatch_latency_ms", "fallback_reason", "error")
    with (directory / "results.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({key: json.dumps(value, ensure_ascii=False) if isinstance(value, (list, dict)) else value for key, value in row.items() if key in fields})
    (directory / "summary.md").write_text(
        "# Reasoning benchmark\n\nWarmup excluded; latency statistics use valid outputs only.\n"
        "Dispatch: before MQTT publish → observer callback receiving matching cmd/request.\n"
        "Hermes: Bridge invocation duration, not TTFT, pure GPU time or ASR/TTS.\n\n```json\n"
        + json.dumps(summary, indent=2) + "\n```\n", encoding="utf-8")
    return summary


def source_hashes() -> dict:
    paths = [*Path(__file__).parent.glob("*.py"), ROOT / "tools/create_mock_event_images.py",
             ROOT / "tools/hermes_resident_server.py",
             ROOT / "hermes-agent/run_agent.py", ROOT / "third_party/hermes/manifest.json",
             *(ROOT / "hermes_temi_bridge/src/hermes_temi_bridge").glob("*.py"),
             *(ROOT / "hermes-agent/skills").glob("temi-*/SKILL.md")]
    return {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(paths)}


def run_benchmark(args, cases) -> Path:
    manifest_path = args.dataset.with_name("dataset.json")
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else None
    if manifest is not None and (manifest.get("schema_version") != "1.0" or manifest.get("cases_file") != args.dataset.name):
        raise ValueError("unsupported or mismatched dataset manifest")
    before = verify_runtime(args)  # no output directory or publication before preflight succeeds
    source = source_hashes()
    args.output_root.mkdir(parents=True, exist_ok=True, mode=0o700)
    directory = args.output_root / (datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "_" + uuid.uuid4().hex[:8])
    directory.mkdir(mode=0o700)
    (directory / "README.md").write_text(README, encoding="utf-8")
    for name in ("README.md",):
        (directory / name).chmod(0o600)
    metadata = {"schema_version": "1.0", "run_id": directory.name, "status": "running",
                "runtime": before, "warmup": args.warmup, "repeat": args.repeat,
                "case_ids": [case.case_id for case in cases],
                "dataset_manifest": manifest,
                "dataset_sha256": hashlib.sha256(args.dataset.read_bytes()).hexdigest(),
                "source_hashes": source,
                "git_head": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
                "timing_scope": "MQTT publish to matching command reception; Bridge Hermes invocation; excludes ASR/TTS",
                "cleanup_requested": args.cleanup_memory_after_case}
    path = directory / "metadata.json"
    def save():
        path.write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    rows = []
    previous_evidence = args.evidence_root
    args.evidence_root = directory / "cleanup"
    args.stop_on_error = True
    save()
    print(f"EVIDENCE_ROOT={directory}", file=sys.stderr, flush=True)
    try:
        for warmup, repetition in [(True, i + 1) for i in range(args.warmup)] + [(False, i + 1) for i in range(args.repeat)]:
            def receive(row, capture):
                result = measurement(row, capture, read_trace(args.trace_dir, row["event_id"]))
                result.update(warmup=warmup, repetition=repetition)
                rows.append(result)
                with (directory / "results.jsonl").open("a", encoding="utf-8") as handle:
                    handle.write(json.dumps(result, ensure_ascii=False) + "\n")
                    handle.flush()
                print(f"CASE_DONE {row['case_id']} warmup={warmup} valid={result['valid_output']} hermes_ms={result['hermes_latency_ms']}", file=sys.stderr, flush=True)
            selected = cases[:1] if warmup else cases
            result = action.run_live(args, selected, capture_factory=TimedCapture, on_result=receive)
            if result["stopped_after_cleanup_refusal"] or any(row.get("error") for row in result["results"]):
                raise ValueError("stopped after timeout/cleanup refusal; late writes may remain, inspect before retrying")
            if warmup and (not rows or not rows[-1]["inference_completed"]):
                raise ValueError("warmup did not complete measured Hermes inference")
        if (verify_runtime(args) != before or source_hashes() != metadata["source_hashes"]
                or hashlib.sha256(args.dataset.read_bytes()).hexdigest() != metadata["dataset_sha256"]):
            raise ValueError("runtime/source/dataset changed during benchmark; do not use for speed comparison")
        metadata["status"] = "completed"
    except BaseException as exc:
        metadata["status"] = "interrupted" if isinstance(exc, KeyboardInterrupt) else "failed"
        metadata["error_class"] = type(exc).__name__
        raise
    finally:
        args.evidence_root = previous_evidence
        metadata["summary"] = write_reports(directory, rows)
        save()
        for artifact in directory.iterdir():
            if artifact.is_file():
                artifact.chmod(0o600)
    return directory




def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.repeat < 1 or args.warmup < 0 or (args.context_length is not None and args.context_length < 1):
            raise ValueError("repeat/context-length must be positive; warmup must be nonnegative")
        for name in ("timeout", "delay"):
            value = getattr(args, name)
            if not math.isfinite(value) or value < 0 or (name == "timeout" and value == 0):
                raise ValueError(f"{name} is invalid")
        cases = action.select_cases(args.case, load_cases(args.dataset))
        if not args.live or args.list:
            summary = action.offline_summary(cases)
            if args.json:
                print(json.dumps(summary, ensure_ascii=False, indent=2))
            else:
                action.print_human(summary)
            return 0
        if not all((args.resident_pid, args.bridge_pid, args.trace_dir)):
            raise ValueError("live requires --resident-pid --bridge-pid --trace-dir")
        if not re.fullmatch(r"[A-Za-z0-9_-]+", args.robot_id):
            raise ValueError("robot-id must contain only letters, numbers, underscore or hyphen")
        print("LIVE BENCHMARK: publishes canonical ASR; connected Temi may execute commands and memory may change.", file=sys.stderr)
        directory = run_benchmark(args, cases)
        metadata = json.loads((directory / "metadata.json").read_text())
        summary = metadata["summary"]
        if args.json:
            print(json.dumps(metadata, ensure_ascii=False, indent=2))
        else:
            print(f"BENCHMARK_DONE evidence={directory} valid={summary['valid_outputs']}/{summary['attempts']}")
        return 0 if summary["valid_outputs"] == len(cases) * args.repeat and summary["consistent_valid_outputs"] == summary["valid_outputs"] else 1
    except (ValueError, OSError, action.EvaluationFailure, subprocess.SubprocessError, KeyError) as exc:
        print(f"BENCHMARK_ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
